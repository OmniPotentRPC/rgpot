"""Cross-check the mixture oracle data against LAMMPS ``pair_style eam/fs``.

The Quantum Sutton-Chen potential is a Finnis-Sinclair potential, so LAMMPS
can evaluate it from tables built from the published equations:

    E_i = F_a(rho_i) + 1/2 sum_j phi_ab(r_ij),      F_a(rho) = -c_a eps_a sqrt(rho)
    rho_i = sum_j f_ab(r_ij),                        f_ab(r) = (a_ab / r)^m_ab
    phi_ab(r) = eps_ab (a_ab / r)^n_ab

with the mixing rules of Eq. (2) of Qi, Cagin, Kimura and Goddard, Phys. Rev. B
59, 3527 (1999). The ``eam/fs`` format allows the density to depend on the
element pair (a, b), which is what the paper's mixed ``a_ij, m_ij`` density
needs (``eam/alloy`` cannot hold it). The tables are cubic-spline sampled, so
agreement is limited by interpolation, not by the equations.

Run with a LAMMPS Python module (conda-forge ``lammps`` provides one)::

    python3 scripts/qsc_reference/lammps_crosscheck.py \\
        --data CppCore/tests/data/qsc/oracle_mixtures.dat

The script exits non-zero when any energy, force or stress component differs
from the oracle data by more than ``--tol`` (relative to the largest value of
that quantity in the case).
"""

from __future__ import annotations

import argparse
import math
import os
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import qsc_common as common  # noqa: E402
import qsc_oracle as oracle  # noqa: E402

N_R = 20001
N_RHO = 30001
RHO_MAX = 300.0
# LAMMPS "metal" units use nktv2p = 1.6021765e6 bar per eV/Angstrom^3.
BAR_TO_EV_A3 = 1.0 / 1.6021765e6


def mixed(za, zb):
    pa = oracle.QSC_TABLE[za]
    pb = oracle.QSC_TABLE[zb]
    return {
        "n": 0.5 * (pa[0] + pb[0]),
        "m": 0.5 * (pa[1] + pb[1]),
        "eps": math.sqrt(pa[2] * pb[2]),
        "a": 0.5 * (pa[4] + pb[4]),
    }


def write_table(path, elements, cutoff):
    dr = cutoff / (N_R - 1)
    drho = RHO_MAX / (N_RHO - 1)
    with open(path, "w", encoding="ascii") as out:
        out.write("QSC eam/fs table from published equations\n")
        out.write("Qi, Cagin, Kimura, Goddard, Phys. Rev. B 59, 3527 (1999)\n")
        out.write("generated by lammps_crosscheck.py\n")
        out.write(f"{len(elements)} " + " ".join(oracle.SYMBOLS[z] for z in elements) + "\n")
        out.write(f"{N_RHO} {drho!r} {N_R} {dr!r} {cutoff!r}\n")
        for za in elements:
            pa = oracle.QSC_TABLE[za]
            out.write(f"{za} 1.0 {pa[4]!r} fcc\n")
            out.write(
                "\n".join(repr(-pa[3] * pa[2] * math.sqrt(k * drho)) for k in range(N_RHO)) + "\n"
            )
            for zb in elements:
                p = mixed(za, zb)
                vals = []
                for k in range(N_R):
                    r = k * dr
                    vals.append(0.0 if k == 0 else (p["a"] / r) ** p["m"])
                out.write("\n".join(repr(v) for v in vals) + "\n")
        for ia, za in enumerate(elements):
            for zb in elements[: ia + 1]:
                p = mixed(za, zb)
                vals = []
                for k in range(N_R):
                    r = k * dr
                    vals.append(0.0 if k == 0 else r * p["eps"] * (p["a"] / r) ** p["n"])
                out.write("\n".join(repr(v) for v in vals) + "\n")


def inside_box(case):
    """Positions moved into the cell; create_atoms drops atoms outside it."""
    if not case.periodic:
        return [[x + 25.0 for x in p] for p in case.pos]
    cell = case.cell
    det = oracle._det3(cell)
    inv = oracle._inverse3(cell)
    out = []
    for p in case.pos:
        frac = [sum(p[k] * inv[k][r] for k in range(3)) for r in range(3)]
        frac = [f - math.floor(f) for f in frac]
        out.append([sum(frac[r] * cell[r][k] for r in range(3)) for k in range(3)])
    assert det > 0
    return out


def run_case(lammps, case, workdir):
    elements = sorted(set(case.species))
    table = os.path.join(workdir, "qsc.eam.fs")
    write_table(table, elements, case.cutoff)
    lmp = lammps.lammps(cmdargs=["-log", "none", "-screen", "none"])
    ax, ay, az = case.cell[0]
    bx, by, bz = case.cell[1]
    cx, cy, cz = case.cell[2]
    assert ay == 0.0 and az == 0.0 and bz == 0.0, "LAMMPS needs a lower-triangular cell"
    lmp.commands_list([
        "units metal",
        "atom_style atomic",
        "atom_modify map array sort 0 0",
        "boundary p p p",
        f"region box prism 0 {ax!r} 0 {by!r} 0 {cz!r} {bx!r} {cx!r} {cy!r} units box",
        f"create_box {len(elements)} box",
    ])
    for z, p in zip(case.species, inside_box(case)):
        lmp.command(
            f"create_atoms {elements.index(z) + 1} single {p[0]!r} {p[1]!r} {p[2]!r} units box"
        )
    for idx in range(len(elements)):
        lmp.command(f"mass {idx + 1} 1.0")
    lmp.commands_list([
        "pair_style eam/fs",
        f"pair_coeff * * {table} " + " ".join(oracle.SYMBOLS[z] for z in elements),
        "neighbor 0.0 bin",
        "neigh_modify delay 0 every 1 check no",
        "thermo_style custom step pe pxx pyy pzz pyz pxz pxy",
        "run 0",
    ])
    n = len(case.species)
    forces = lmp.gather_atoms("f", 1, 3)
    energy = lmp.get_thermo("pe")
    stress = [-lmp.get_thermo(k) * BAR_TO_EV_A3 for k in ("pxx", "pyy", "pzz", "pyz", "pxz", "pxy")]
    lmp.close()
    return energy, [[forces[3 * i + k] for k in range(3)] for i in range(n)], stress


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--data", required=True)
    ap.add_argument("--tol", type=float, default=1e-7)
    args = ap.parse_args(argv)
    import lammps

    _, cases = common.read_cases(args.data)
    worst = 0.0
    with tempfile.TemporaryDirectory(prefix="qsc-lammps-") as workdir:
        for case in cases:
            e, f, s = run_case(lammps, case, workdir)
            de = abs(e - float(case.energy)) / abs(float(case.energy))
            fscale = max(abs(float(x)) for row in case.forces for x in row)
            df = max(abs(f[i][k] - float(case.forces[i][k])) for i in range(len(f)) for k in range(3)) / fscale
            ds = 0.0
            if case.stress is not None:
                sscale = max(abs(float(x)) for x in case.stress)
                ds = max(abs(a - float(b)) for a, b in zip(s, case.stress)) / sscale
            print(f"{case.name:26s} energy {de:9.2e}  force {df:9.2e}  stress {ds:9.2e}")
            worst = max(worst, de, df, ds)
    print(f"worst relative deviation {worst:.2e} (tolerance {args.tol:.1e})")
    return 0 if worst <= args.tol else 1


if __name__ == "__main__":
    sys.exit(main())
