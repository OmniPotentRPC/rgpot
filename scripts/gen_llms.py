#!/usr/bin/env python3
# Copyright 2023--present rgpot developers
"""Generate ``llms.txt`` and ``llms-full.txt`` from the documentation sources.

``llms.txt`` follows https://llmstxt.org: a title, a one paragraph summary, and
sections of links with a short note for each.  ``llms-full.txt`` holds the
text of every page the links name, converted from org (or copied, for the
Markdown notes) into plain Markdown, in the order of the table of contents.

The pages and their order come from the ``toctree`` directives of
``docs/orgmode/index.org`` and the pages it names.  Nothing is read from the
network and nothing depends on the clock, so a run on an unchanged tree
produces identical bytes.

Usage::

    python scripts/gen_llms.py            # write llms.txt and llms-full.txt
    python scripts/gen_llms.py --check    # fail when either file is stale

The module uses the standard library only.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SITE = "https://rgpot.rgoswami.me/"
INDEX = "docs/orgmode/index.org"
ORG_ROOT = "docs/orgmode"
# `docs/notes/<name>` pages are copied from `docs/<name>.md` by the docs build.
NOTES_DIR = "docs"
# Sections that go under "Optional" in llms.txt: a reader short of context may
# skip them.
OPTIONAL_CAPTIONS = ("Development", "Notes")
# Entries with no source in the tree (generated by Doxygen or Sphinx).
GENERATED = {"api/index"}
DESCRIPTION_LIMIT = 220


@dataclass
class Page:
    caption: str
    key: str  # toctree entry relative to docs/orgmode, e.g. "howto/ipi"
    path: Path  # source file
    title: str
    summary: str
    body: str  # converted Markdown, without the title

    @property
    def url(self) -> str:
        return SITE + self.key + ".html"


# ---------------------------------------------------------------- reading


def _read(path: Path) -> str:
    return path.read_text(encoding="utf-8").replace("\r\n", "\n")


def _toctree_entries(text: str) -> list[tuple[str, list[str]]]:
    """(caption, entries) for each toctree directive in an org page."""
    out = []
    lines = text.split("\n")
    i = 0
    while i < len(lines):
        if lines[i].strip() == ".. toctree::":
            caption = ""
            entries: list[str] = []
            i += 1
            while i < len(lines) and (lines[i].startswith("   ") or not lines[i].strip()):
                stripped = lines[i].strip()
                if stripped.startswith(":caption:"):
                    caption = stripped.split(":caption:", 1)[1].strip()
                elif stripped and not stripped.startswith(":"):
                    entries.append(stripped)
                i += 1
            out.append((caption, entries))
            continue
        i += 1
    return out


def _resolve(root: Path, base_key: str, entry: str) -> tuple[str, Path] | None:
    """Toctree entry of the page ``base_key`` -> (key, source path)."""
    base = Path(base_key).parent
    key = (base / entry).as_posix() if str(base) != "." else entry
    if key in GENERATED:
        return None
    org = root / ORG_ROOT / (key + ".org")
    if org.is_file():
        return key, org
    if key.startswith("notes/"):
        md = root / NOTES_DIR / (key.split("/", 1)[1] + ".md")
        if md.is_file():
            return key, md
    return None


def collect(root: Path = ROOT) -> list[tuple[str, str, Path]]:
    """Every page in table of contents order: (caption, key, path)."""
    pages: list[tuple[str, str, Path]] = []
    seen: set[str] = set()

    def walk(key: str, path: Path, caption: str) -> None:
        if path.suffix != ".org":
            return
        for cap, entries in _toctree_entries(_read(path)):
            for entry in entries:
                found = _resolve(root, key, entry)
                if found is None:
                    continue
                child_key, child = found
                if child_key in seen:
                    continue
                seen.add(child_key)
                pages.append((cap or caption, child_key, child))
                walk(child_key, child, cap or caption)

    index = root / INDEX
    walk("index", index, "")
    return pages


# -------------------------------------------------------------- converting


_KEYWORD = re.compile(r"^#\+(?!begin|end)", re.I)
_BEGIN = re.compile(r"^#\+begin_(\w+)\s*(.*)$", re.I)
_END = re.compile(r"^#\+end_(\w+)\s*$", re.I)
_HEADING = re.compile(r"^(\*+)\s+(.*)$")
_LINK = re.compile(r"\[\[([^\]]+)\](?:\[([^\]]+)\])?\]")
_VERBATIM = re.compile(r"(?<![\w=~])([=~])([^\s=~](?:.*?[^\s=~])?)\1(?![\w=~])")
_DOC_ROLE = re.compile(r":doc:`(?:[^`<]*<([^>]+)>|([^`]+))`")


def _title(text: str, fallback: str) -> str:
    m = re.search(r"^#\+TITLE:\s*(.+)$", text, re.M | re.I)
    return m.group(1).strip() if m else fallback


def _link_target(target: str, page_key: str) -> str:
    if target.startswith("file:"):
        path = target[len("file:") :].split("::", 1)[0]
        if path.endswith(".org"):
            base = Path(page_key).parent
            resolved = (base / path[: -len(".org")]).as_posix()
            parts: list[str] = []
            for part in resolved.split("/"):
                if part == "..":
                    if parts:
                        parts.pop()
                elif part != ".":
                    parts.append(part)
            return SITE + "/".join(parts) + ".html"
        return path
    return target


def _inline(line: str, page_key: str) -> str:
    def link(m: re.Match) -> str:
        target = _link_target(m.group(1), page_key)
        text = m.group(2) or target
        return f"[{text}]({target})"

    line = _LINK.sub(link, line)
    line = _DOC_ROLE.sub(lambda m: "`" + (m.group(1) or m.group(2)).strip() + "`", line)
    return _VERBATIM.sub(lambda m: "`" + m.group(2) + "`", line)


def org_to_markdown(text: str, page_key: str) -> str:
    out: list[str] = []
    block: str | None = None
    skip_export = False
    for line in text.split("\n"):
        begin = _BEGIN.match(line)
        end = _END.match(line)
        if skip_export:
            if end and end.group(1).lower() == "export":
                skip_export = False
            continue
        if block is not None:
            if end and end.group(1).lower() == block:
                out.append("```" if block in ("src", "example") else "")
                block = None
            else:
                out.append(line[1:] if line.startswith(",") and line[1:2] in ("*", "#") else line)
            continue
        if begin:
            kind = begin.group(1).lower()
            if kind == "export":
                skip_export = True
            elif kind == "src":
                lang = begin.group(2).split()[0] if begin.group(2).strip() else ""
                out.append("```" + lang)
                block = "src"
            elif kind == "example":
                out.append("```")
                block = "example"
            elif kind == "quote":
                out.append("")
                block = "quote"
            else:
                block = kind
            continue
        if _KEYWORD.match(line):
            continue
        heading = _HEADING.match(line)
        if heading:
            out.append("#" * (len(heading.group(1)) + 1) + " " + _inline(heading.group(2), page_key))
            continue
        if line.startswith("|-"):
            out.append(re.sub(r"\+", "|", line))
            continue
        out.append(_inline(line, page_key).rstrip())
    body = "\n".join(out)
    body = re.sub(r"\n{3,}", "\n\n", body).strip("\n")
    return body


def _first_paragraph(markdown: str) -> str:
    paragraph: list[str] = []
    fenced = False
    for line in markdown.split("\n"):
        if line.startswith("```"):
            fenced = not fenced
            continue
        if fenced:
            continue
        stripped = line.strip()
        if not stripped or stripped.startswith(("#", "|", "- ", "* ", ">", "!", ".. ")):
            if paragraph:
                break
            continue
        paragraph.append(stripped)
    text = " ".join(paragraph)
    text = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", text)
    text = text.replace("`", "")
    sentence = re.match(r"(.+?[.:])(?=\s+[A-Z]|$)", text)
    text = sentence.group(1) if sentence else text
    if len(text) > DESCRIPTION_LIMIT:
        text = text[: DESCRIPTION_LIMIT - 3].rsplit(" ", 1)[0] + "..."
    return text


def markdown_page(text: str, fallback: str) -> tuple[str, str]:
    lines = text.split("\n")
    title = fallback
    for i, line in enumerate(lines):
        if line.startswith("# "):
            title = line[2:].strip()
            lines = lines[i + 1 :]
            break
    body = "\n".join(lines).strip("\n")
    body = re.sub(r"^(#+) ", lambda m: "#" * (len(m.group(1)) + 1) + " ", body, flags=re.M)
    return title, body


def load_pages(root: Path = ROOT) -> list[Page]:
    pages = []
    for caption, key, path in collect(root):
        text = _read(path)
        if path.suffix == ".org":
            title = _title(text, key)
            body = org_to_markdown(text, key)
            if body.startswith("## "):
                first, _, rest = body.partition("\n")
                if first[3:].strip() == title.strip():
                    body = rest.strip("\n")
        else:
            title, body = markdown_page(text, key)
        pages.append(Page(caption, key, path, title, _first_paragraph(body), body))
    return pages


# --------------------------------------------------------------- rendering


def _summary(root: Path) -> str:
    index = org_to_markdown(_read(root / INDEX), "index")
    m = re.search(r"^## Overview\n+(.*?)(?:\n\n|\Z)", index, re.S | re.M)
    paragraph = " ".join(m.group(1).split()) if m else "rgpot is a potential energy library."
    return paragraph


def render_llms(pages: list[Page], root: Path = ROOT) -> str:
    lines = [
        "<!-- Copyright 2023--present rgpot developers -->",
        "",
        "# rgpot",
        "",
        "> " + _summary(root),
        "",
        "The pages below are the documentation of the repository at "
        "https://github.com/OmniPotentRPC/rgpot.",
        "`llms-full.txt` holds the text of every page in one file.",
        "`AGENTS.md` in the repository root says how to build, test and "
        "contribute.",
    ]
    captions: list[str] = []
    for page in pages:
        if page.caption not in captions:
            captions.append(page.caption)
    ordered = [c for c in captions if c not in OPTIONAL_CAPTIONS] + [c for c in captions if c in OPTIONAL_CAPTIONS]
    optional_started = False
    for caption in ordered:
        optional = caption in OPTIONAL_CAPTIONS
        if optional and not optional_started:
            lines += ["", "## Optional"]
            optional_started = True
        heading = f"### {caption}" if optional else f"## {caption or 'Pages'}"
        lines += ["", heading, ""]
        for page in pages:
            if page.caption != caption:
                continue
            note = f": {page.summary}" if page.summary else ""
            lines.append(f"- [{page.title}]({page.url}){note}")
    return "\n".join(lines) + "\n"


def render_full(pages: list[Page], root: Path = ROOT) -> str:
    out = [
        "<!-- Copyright 2023--present rgpot developers -->",
        "",
        "# rgpot documentation",
        "",
        "> The text of every documentation page of rgpot, in the order of its table of "
        "contents. See llms.txt for the index and AGENTS.md for the contributor rules.",
    ]
    for page in pages:
        out += ["", "---", "", f"# {page.title}", "", f"Source: {page.path.relative_to(root).as_posix()}", f"URL: {page.url}", ""]
        out.append(page.body)
    return "\n".join(out).rstrip("\n") + "\n"


def generate(root: Path = ROOT) -> dict[str, str]:
    pages = load_pages(root)
    return {"llms.txt": render_llms(pages, root), "llms-full.txt": render_full(pages, root)}


def stale(root: Path = ROOT) -> list[str]:
    """One message for each generated file that differs from the sources."""
    problems = []
    for name, text in generate(root).items():
        path = root / name
        if not path.is_file():
            problems.append(f"{name} is missing; run python scripts/gen_llms.py")
        elif path.read_text(encoding="utf-8") != text:
            problems.append(f"{name} is stale; run python scripts/gen_llms.py")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail when a generated file is stale")
    parser.add_argument("--root", type=Path, default=ROOT)
    args = parser.parse_args(argv)
    if args.check:
        problems = stale(args.root)
        for problem in problems:
            print(problem, file=sys.stderr)
        if problems:
            return 1
        print("gen_llms: clean")
        return 0
    for name, text in generate(args.root).items():
        (args.root / name).write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {name} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
